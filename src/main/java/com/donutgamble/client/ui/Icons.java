	private final String[] rows;

	Icons(String... rows) {
		this.rows = rows;
	}

	/** Draws at (x, y), 8×8, in one color. */
	public void draw(DrawContext ctx, int x, int y, int color) {
		for (int r = 0; r < rows.length; r++) {
			String row = rows[r];
			int start = -1;
			for (int c = 0; c <= row.length(); c++) {
				boolean on = c < row.length() && row.charAt(c) == '#';
				if (on && start < 0) {
					start = c;
				} else if (!on && start >= 0) {
					ctx.fill(x + start, y + r, x + c, y + r + 1, color);
					start = -1;
				}
			}
		}
	}
